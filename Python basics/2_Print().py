# Print():- Use for display output in screen

"""----------Escaps sequences-----------"""
# \" -> Double quote
# \' -> Single quote
# \\ -> Back slash
# \n -> New line
# \t -> Tab
# \b -> Back space

print("print(\"This is first code in python!\")")
print("This is first code in python!")
print('-' * 40)

print("print('This is also print')")
print('This is also print')
print('-' * 40)

print("print(\"Hi 'python'\")")
print("Hi 'python'")
print('-' * 40)

print("print('Hi \"python\"')")
print('Hi "python"')
print('-' * 40)

print("print(\"Hi \"python\"\")")
print("Hi \"python\"")
print('-' * 40)

# print:- path:C:\users\liptan
print("print(\"path:c:\\users\\liptan\")")
print("path:c:\\users\\liptan")
print('-' * 40)

# '\n' -> add next line
print("liptan and kumar print sepret line!")
# 1 -> way
print("liptan")
print("kumar")
print('-' * 40)
# 2 -> way
print("liptan\nkumar")
print('-' * 40)

# '\t' -> add tab
print("liptan and kumar btw add tab line!")
print("liptan\tkumar")
print("\tliptan kumar")
print("liptan\n\tkumar")
print('-' * 40)

