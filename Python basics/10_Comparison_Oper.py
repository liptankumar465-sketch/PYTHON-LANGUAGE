# Comparison Operators
# Syntax:- val1 comOper val2 => True/False

# Numbers
print(10 == 10)
print(10 != 10)
print(7 > 3)
print(7 >= 3)
print(3 < 7)
print(7 <= 7)

# strings
print("a" == "A")
print("a" != "A")
print("a" == "a")
print("a" != "a")
print("a" < "b")

# Chaining rule
print(1 < 5 < 10)
print(1 < 10 < 5)

